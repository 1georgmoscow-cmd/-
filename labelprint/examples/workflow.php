#!/usr/bin/env php
<?php
declare(strict_types=1);

/**
 * Складской процесс целиком, как он выглядит из вашего кода.
 *
 *   1. PDF появился в /upload/pdf
 *   2. берём готовый ZPL
 *   3. печатаем
 *   4. оператор наклеил и просканировал — сверяем
 *
 * Запуск:  php examples/workflow.php ozon.pdf 192.168.1.50
 */

require __DIR__ . '/../src/bootstrap.php';

use LabelPrint\Api;

$path = $argv[1] ?? 'ozon.pdf';          // путь ОТНОСИТЕЛЬНО pdf_dir из конфига
$printerHost = $argv[2] ?? null;         // адрес принтера; без него печать пропускается

$api = Api::boot();

// ---------------------------------------------------------------------------
// 1. Берём готовую этикетку
//
// Обычно её уже отрендерил воркер — тогда это просто чтение строки из MySQL.
// renderIfMissing: true нужен для случая «файл появился секунду назад, ждать
// воркер некогда»: тогда рендеринг произойдёт прямо здесь, примерно за 100 мс.
// ---------------------------------------------------------------------------
$label = $api->label($path, renderIfMissing: true);

if ($label === null) {
    fwrite(STDERR, "Этикетка для {$path} не найдена\n");
    exit(1);
}

printf(
    "Этикетка #%d: %d×%d точек при %d dpi, ZPL %s байт, профиль %s\n",
    $label->id,
    $label->widthDots,
    $label->heightDots,
    $label->dpi,
    number_format(strlen($label->zpl)),
    $label->profileCode,
);

// ---------------------------------------------------------------------------
// 2. Что должен увидеть сканер
//
// Проверяем ДО печати: этикетка без единого распознанного кода не может быть
// подтверждена оператором. Лучше узнать об этом сейчас, чем когда она уже
// наклеена на коробку.
// ---------------------------------------------------------------------------
if (!$label->hasCodes()) {
    fwrite(STDERR, "ВНИМАНИЕ: на этикетке не распознано ни одного кода — сканер её не подтвердит\n");
} else {
    printf("Ожидаемый код: %s\n", $label->barcode);
}

// ---------------------------------------------------------------------------
// 3. Печать
//
// Это просто запись байтов в сокет: на сетевой принтер уходит около 0,5 мс.
// Многостраничный файл отправляется одной посылкой: $api->zpl($path).
// ---------------------------------------------------------------------------
if ($printerHost !== null) {
    try {
        $started = hrtime(true);
        $api->send($label->zpl, $printerHost);
        printf("Отправлено на %s за %.1f мс\n", $printerHost, (hrtime(true) - $started) / 1e6);
    } catch (RuntimeException $e) {
        fwrite(STDERR, 'Печать не удалась: ' . $e->getMessage() . "\n");
        exit(1);
    }
} else {
    echo "Адрес принтера не задан, печать пропущена\n";
}

// ---------------------------------------------------------------------------
// 4. Сверка после наклейки
//
// Сюда придёт то, что ввёл сканер штрихкода. Сравнение учитывает и исходные
// байты, и вид без управляющих символов: ручные сканеры по-разному обходятся
// с разделителем GS, и сравнение по одному варианту давало бы ложные отказы.
// ---------------------------------------------------------------------------
$scanned = $label->barcode ?? 'НИЧЕГО-НЕ-ОТСКАНИРОВАНО';

if ($api->verify($label->id, $scanned)) {
    printf("СВЕРКА ПРОЙДЕНА: наклеена та этикетка (%s)\n", $scanned);
} else {
    printf("СВЕРКА НЕ ПРОЙДЕНА: наклеено %s, а ожидалось %s\n", $scanned, $label->barcode ?? '(нет кода)');
    exit(1);
}

// ---------------------------------------------------------------------------
// 5. Обратный поиск: сканер дал код, надо понять, чья это этикетка
// ---------------------------------------------------------------------------
foreach ($api->findByCode($scanned) as $found) {
    printf("  код принадлежит: %s, стр. %d, профиль %s\n", $found['path'], $found['page_no'], $found['profile_code']);
}
